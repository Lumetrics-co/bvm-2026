/** Human-readable alt text derived from a logo's filename. */
export function altFromSrc(src: string): string {
  const file = src.split("/").pop() ?? src;
  return file.replace(/\.[^.]+$/, "").replace(/[-_]+/g, " ").trim() || "Partner logo";
}
